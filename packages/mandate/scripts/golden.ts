// Writes golden vectors consumed by tools/verify-py (the independent Python implementation) and the web app.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import type { Address } from "viem";
import { loadDeployment } from "@yinglong/sdk/server";
import { canonicalJson, compileMandate, decompile, hashRingAscii, hashRingGeometry, namesFor, nadiaMandate, lotusShenzhenMandate } from "../src/index";

const d = loadDeployment("anvil");
const A = (n: number) => `0x${n.toString(16).padStart(40, "0")}` as Address;
const NOW = 1_792_000_000;
const docs = {
  nadia: nadiaMandate(d, { account: A(0xa11ce), agent: A(1), harbourHomes: A(0x101), hbuBursar: A(0x102), foodMart: A(0x103), issuerHbu: A(0x201), issuerBank: A(0x202) }, { now: NOW }),
  lotus: lotusShenzhenMandate(d, { account: A(0xb0b), agent: A(2), shenzhenComponents: A(0x301), payroll: A(0x302), issuerBank: A(0x202) }, { now: NOW }),
};
for (const [name, m] of Object.entries(docs)) {
  const c = compileMandate(m, d);
  const { rules, sentences } = decompile(c.caveats, d, namesFor(d, m));
  const out = {
    description: "Golden vector generated by packages/mandate/scripts/golden.ts; do not edit by hand.",
    deployment: "contracts/deployments/anvil.json",
    mandate: m,
    canonicalJson: canonicalJson(m),
    mandateHash: c.mandateHash,
    lineageIdHash: c.lineageIdHash,
    delegation: { delegate: c.delegation.delegate, delegator: c.delegation.delegator, authority: c.delegation.authority, salt: c.delegation.salt.toString() },
    caveats: c.caveats,
    delegationHash: c.delegationHash,
    rules: JSON.parse(JSON.stringify(rules, (_, v) => (typeof v === "bigint" ? v.toString() : v))),
    sentences,
    hashRing: hashRingGeometry(c.delegationHash),
    hashRingRevoked: hashRingGeometry(c.delegationHash, { revoked: true }),
    hashRingAscii: hashRingAscii(c.delegationHash),
  };
  writeFileSync(resolve(import.meta.dirname, "..", "golden", `${name}.json`), `${JSON.stringify(out, null, 2)}\n`);
  console.log(`golden/${name}.json ${c.delegationHash}`);
}
