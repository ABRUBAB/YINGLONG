#!/usr/bin/env node
// Regenerates the results block of infra/fisco/README.md (between the "generated" markers) from the
// JSON written by the code: infra/fisco/chain-facts.json, contracts-fisco/reports/probe-*.json,
// contracts-fisco/deployments/fisco-spike.json and contracts-fisco/reports/codehash-compare-*.json.
// No number in the block is typed by hand.
//
// Usage (repo root): node infra/fisco/render-readme.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..");
const CF = join(REPO, "contracts-fisco");
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const latest = (dir, prefix) => {
  const files = readdirSync(dir).filter((f) => f.startsWith(prefix) && f.endsWith(".json") && !f.includes("-anvil")).sort();
  if (!files.length) throw new Error(`no ${prefix}*.json in ${dir}`);
  return join(dir, files[files.length - 1]);
};

const factsPath = join(HERE, "chain-facts.json");
const probePath = latest(join(CF, "reports"), "probe-");
const spikePath = join(CF, "deployments", "fisco-spike.json");
const comparePath = latest(join(CF, "reports"), "codehash-compare-");
const facts = readJson(factsPath);
const probe = readJson(probePath);
const spike = readJson(spikePath);
const compare = readJson(comparePath);
const P = probe.results;
const rel = (p) => p.slice(REPO.length + 1).replaceAll("\\", "/");

const yes = (b) => (b === true ? "yes" : b === false ? "no" : String(b));
const code = (s) => `\`${s}\``;
const short = (h, n = 10) => (typeof h === "string" && h.length > 2 * n ? `${h.slice(0, n + 2)}...${h.slice(-4)}` : h);
const table = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const n = (v) => Number(v).toLocaleString("en-US");

const lines = [];
const h = (s) => lines.push("", s, "");
const p = (s) => lines.push(s);

lines.push(`_Generated by ${code("node infra/fisco/render-readme.mjs")} from ${code(rel(factsPath))}, ${code(rel(probePath))}, ${code(rel(spikePath))} and ${code(rel(comparePath))}. Do not edit by hand._`);

// ------------------------------------------------------------------------------------------------
h("### Chain facts (collected on the server)");
const sc = facts.systemConfig;
p(table(["Item", "Value"], [
  ["fisco-bcos", `${facts.binary.version} (${facts.binary.buildType}), commit ${code(short(facts.binary.gitCommit, 8))}, binary sha256 ${code(short(facts.binary.sha256))}`],
  ["Release tarball / build_chain.sh sha256", `${code(short(facts.binary.releaseTarballSha256))} / ${code(short(facts.binary.buildChainShSha256))}`],
  ["Genesis sha256 (identical on all 5 nodes)", `${code(short(facts.genesis.sha256))} (${yes(facts.genesis.identicalOnAllNodes)})`],
  ["sm_crypto / auth check / executor version", `${facts.genesis.smCrypto} / ${facts.genesis.authCheck} / ${facts.genesis.executorVersion}`],
  ["chain / group", `${facts.genesis.chainId} / ${facts.genesis.groupId}`],
  ["Genesis [features]", Object.entries(facts.genesis.features).map(([k, v]) => `${k}=${v}`).join(", ")],
  ["eth_chainId", `${facts.web3.ethChainId} (${Number(BigInt(facts.web3.ethChainId))})`],
  ["Consensus", `PBFT, min_seal_time ${facts.consensus.minSealTimeMs} ms, ${facts.consensus.sealers.length} sealers, ${facts.consensus.observers.length} observer`],
  ["addObserver(node4) tx", `${code(facts.consensus.addObserverTx.hash)} (block ${Number(facts.consensus.addObserverTx.blockNumber)}, status ${facts.consensus.addObserverTx.status}, to ${code(facts.consensus.addObserverTx.to)})`],
  ["fisco-bcos sockets", facts.fiscoListeners.every((l) => l.startsWith("127.0.0.1:")) ? `all ${facts.fiscoListeners.length} on 127.0.0.1` : facts.fiscoListeners.join(", ")],
  ["Non-loopback listeners on the host", facts.nonLoopbackListenersOnHost.join(", ")],
  ["Collected at", facts.collectedAt],
]));
h("System config read back through the SystemConfigPrecompiled (`getValueByKey`, value / enable block; `\"\" / -1` means never set, i.e. off):");
p(table(["Key", "Value", "Enabled from block"], Object.entries(sc).map(([k, v]) => [code(k), v.value === "" ? "(unset)" : code(v.value), v.enableBlock])));
h("Nodes:");
p(table(["Node", "Role", "Node ID", "P2P", "Native RPC", "Web3 RPC", "systemd unit", "State"],
  facts.nodes.map((x) => [x.node, x.role, code(short(x.nodeId, 8)), x.p2p, x.nativeRpc, x.web3Rpc, code(x.systemdUnit), `${x.active}, ${x.enabled}, Restart=${x.restartPolicy}`])));

// ------------------------------------------------------------------------------------------------
h(`### Probe results (${probe.generatedAt})`);
const ctx = P.evmContext;
const bt = P.blockTime;
const sz = P.contractSizeLimits;
const largestRuntime = Object.entries(sz).filter(([k, v]) => k.startsWith("runtime_") && v.status === "0x1").map(([k]) => Number(k.split("_")[1])).sort((a, b) => b - a)[0];
const initOk = Object.entries(sz).filter(([k, v]) => k.startsWith("initcode_") && v.status === "0x1").map(([k]) => Number(k.split("_")[1]));
const initRejected = Object.entries(sz).filter(([k, v]) => k.startsWith("initcode_") && v.rejected).map(([k, v]) => `${n(k.split("_")[1])} (${v.rejected.replace("eth_sendRawTransaction: ", "")})`);
const gl = P.gasLimits;
const est = P.estimateGas;
const rm = P.rpcMethods;
const supported = Object.entries(rm).filter(([, v]) => v.ok).map(([k]) => k);
const unsupported = Object.entries(rm).filter(([, v]) => !v.ok).map(([k]) => k);
const logs = P.ethGetLogs;
const p256 = P.p256;
const cr = P.fiscoCryptoPrecompile0x100a;
const so = P.ethCallStateOverride;
const rev = P.revertOnChainAndReplay;
p(table(["Question", "Observed on FISCO", "Report field"], [
  ["eth_chainId", `${P.chain.ethChainId} (${P.chain.ethChainIdDecimal})`, "chain"],
  ["CHAINID opcode inside a contract", `${ctx.inTransaction.chainId} in a mined tx, ${ctx.inEthCall.chainId} in eth_call; equals eth_chainId: ${yes(ctx.chainIdOpcodeEqualsEthChainId)}`, "evmContext"],
  ["TIMESTAMP units", `${ctx.timestampUnits} (block.timestamp ${ctx.inTransaction.timestamp}, ${ctx.timestampVsWallClockSec} s from wall clock); RPC header timestamp in ${ctx.headerTimestampUnits}`, "evmContext"],
  ["Other context opcodes", `block.gaslimit ${n(ctx.inTransaction.gasLimit)}, basefee ${ctx.inTransaction.baseFee}, coinbase ${code(ctx.inTransaction.coinbase)}, prevrandao ${ctx.inTransaction.prevrandao}, gasprice ${ctx.inTransaction.gasPrice}; BLOCKHASH(n-1) equals RPC parent hash: ${yes(ctx.blockhashOpcodeMatchesRpcParentHash)}`, "evmContext"],
  ["Block time", `blocks only when transactions are pending (${bt.blocksProducedWhileIdle5s} blocks in 5 s idle); submit-to-receipt median ${bt.submitToReceiptMedianMs} ms (min ${bt.submitToReceiptMinMs}, max ${bt.submitToReceiptMaxMs}) over the SSH tunnel`, "blockTime"],
  ["Legacy (type 0) required?", P.txType2.accepted ? `no: type 2 accepted (status ${P.txType2.status}, reported type ${P.txType2.reportedType}); type 0 also works` : `type 2 rejected: ${P.txType2.error}`, "txType2, txType0Details"],
  ["Legacy tx as reported by eth_getTransactionByHash", `type ${P.txType0Details.transaction.type}, chainId ${P.txType0Details.transaction.chainId}, v ${P.txType0Details.transaction.v} (y-parity, not EIP-155 v), gasPrice ${P.txType0Details.transaction.gasPrice}`, "txType0Details"],
  ["Max contract size", `no EIP-170 limit: runtimes up to ${n(largestRuntime)} bytes deployed; initcode ${initOk.map(n).join(", ")} bytes accepted, ${initRejected.join(", ")} rejected (EIP-3860 limit enforced at the RPC)`, "contractSizeLimits"],
  ["Gas limit", `eth_getBlockByNumber gasLimit ${n(P.chain.latestBlock.gasLimitDecimal)}; EVM block.gaslimit ${n(ctx.inTransaction.gasLimit)} (= system tx_gas_limit); tx with gas 3,000,000,001 accepted: ${yes(gl.txGas_3000000001?.accepted)}`, "gasLimits"],
  ["Gas price", `eth_gasPrice ${P.chain.gasPrice}, baseFeePerGas ${P.chain.latestBlock.baseFeePerGas}`, "chain"],
  ["EXTCODEHASH", `contract: equals keccak256(eth_getCode) ${yes(P.extcodehash.selfMatchesKeccakOfCode)}; EOA with nonce: ${code(short(P.extcodehash.eoaWithNonce, 6))} (keccak256("") on Ethereum: ${yes(P.extcodehash.eoaIsKeccakOfEmpty)}); non-existent: zero ${yes(P.extcodehash.nonExistentIsZero)}`, "extcodehash"],
  ["CREATE address", `Ethereum formula keccak(rlp(sender, nonce)) for a top-level web3 deploy: ${yes(P.deployLegacyType0.createAddressMatchesEvmFormula)}; for CREATE inside a contract (contract nonce starts at 1): ${yes(P.createAddress.matchesEvmFormulaAtNonce1)}`, "deployLegacyType0, createAddress"],
  ["CREATE2", `works: ${yes(P.create2.works)} (actual = in-contract prediction = off-chain prediction)`, "create2"],
  ["P-256 precompile 0x100 (RIP-7212)", `${p256.precompile0x100.available ? "available" : "absent"}: direct eth_call errors, staticcall from a contract returns success with ${p256.precompile0x100.viaContract.returnLength} bytes; the framework's verifier falls back to the SCL Solidity verifier: valid signature accepted ${yes(p256.frameworkVerifier.validSignatureAccepted)}, tampered rejected ${yes(p256.frameworkVerifier.tamperedSignatureRejected)}, eth_estimateGas ${n(p256.frameworkVerifier.estimateGasForVerify)} gas`, "p256"],
  ["Crypto precompile 0x...100a", `answers. sm3("abc") matches the GB/T 32905 vector: ${yes(cr.sm3MatchesGbtVector)}; keccak256Hash matches the opcode: ${yes(cr.keccakMatchesOpcode)}; sm2Verify valid signature: ${yes(cr.sm2Verify.validSignatureVerified)}, returned account = right160(sm3(pub)): ${yes(cr.sm2Verify.accountMatches)}, wrong message rejected: ${yes(cr.sm2Verify.wrongMessageRejected)}`, "fiscoCryptoPrecompile0x100a"],
  ["sm2Verify convention", `${cr.sm2Verify.convention}; a signature over M itself (no Z_A) is rejected: ${yes(cr.sm2Verify.signatureOverRawMWithoutZaRejected)}`, "fiscoCryptoPrecompile0x100a"],
  ["eth_getLogs", `works (${yes(logs.works)}) but the filter must carry address, topics, fromBlock and toBlock keys; topic matching is case-sensitive (lowercase hex works, mixed case returns 0); blockHash filters rejected. eth_newFilter + eth_getFilterLogs: ${logs.newFilterThenGetFilterLogs.ok ? `${logs.newFilterThenGetFilterLogs.count} logs` : logs.newFilterThenGetFilterLogs.error}`, "ethGetLogs.filterShapes"],
  ["eth_call with state overrides", `silently ignored: stateDiff applied ${yes(so.stateDiffApplied)}, code override applied ${yes(so.codeOverrideApplied)} (no error is returned)`, "ethCallStateOverride"],
  ["eth_call block tag", `ignored: a call at an older block returns the latest state (${yes(P.historicalEthCall.blockTagHonoured)} honoured)`, "historicalEthCall"],
  ["eth_estimateGas", `exact (estimate minus gasUsed: ping ${est.ping.estimateMinusGasUsed}, burn ${est["burn(200)"].estimateMinusGasUsed}, deploy ${est["deploy ProbeChild"].estimateMinusGasUsed}); sending with exactly the estimate succeeds; a reverting call returns JSON-RPC error code ${est["revert failWith"].error?.code} with an empty message and the ABI-encoded revert data in error.data; gas metering differs from Ethereum (a small contract deployment used ${n(est["deploy ProbeChild"].estimate)} gas)`, "estimateGas"],
  ["Reverted transaction", `mined with status ${rev.receiptStatus}; the receipt carries no revert data; eth_call replay returns it (decoded: ${code(rev.replayAtParentBlock.decoded?.reason)})`, "revertOnChainAndReplay"],
  ["Native value", P.nativeValue.accepted ? `a tx with value 1 wei is mined but reverts (status ${P.nativeValue.status}): ${code(P.nativeValue.replay?.decoded?.reason)} (feature_balance off)` : `rejected: ${P.nativeValue.error}`, "nativeValue"],
  ["Cancun opcodes at runtime", Object.entries(P.cancunOpcodesAtRuntime).map(([k, v]) => `${k} ${v.works ? "works" : "fails"}`).join(", ") + " (executor v1 always runs the Cancun revision)", "cancunOpcodesAtRuntime"],
  ["Nonce", `eth_getTransactionCount latest ${P.nonces.latest}, pending ${P.nonces.pending}`, "nonces"],
  ["debug_traceTransaction", P.debugTrace.supported ? "supported" : `not supported (${P.debugTrace.error?.message})`, "debugTrace"],
  ["RPC methods answered", supported.map(code).join(", "), "rpcMethods"],
  ["RPC methods not available", unsupported.map(code).join(", "), "rpcMethods"],
]));
h("eth_getLogs filter shapes:");
p(table(["Filter", "Result"], Object.entries(logs.filterShapes).map(([k, v]) => [k, v.ok ? `ok, ${v.count} logs` : `error: ${v.error}`])));

// ------------------------------------------------------------------------------------------------
h(`### Delegation Framework v1.3.0 spike on FISCO (${spike.generatedAt})`);
const v = spike.verdict;
p(`**Verdict: ${v.go ? "GO" : "NO-GO"}.** ` + [
  `all framework contracts deployed: ${yes(v.allFrameworkContractsDeployed)}`,
  `deployed runtime equals the compiled artifact (immutables aside): ${yes(v.runtimeMatchesArtifactForAll)}`,
  `delegation signature valid through ERC-1271: ${yes(v.delegationSignatureValidViaErc1271)}`,
  `redemption within the cap: ${yes(v.redemptionWithinCapSucceeded)}`,
  `redemption above the cap reverted: ${yes(v.redemptionAboveCapReverted)} with ${code(v.revertReason)}`,
  `redemption exactly to the cap: ${yes(v.boundaryRedemptionSucceeded)}`,
].join("; ") + ".");
h("Deployed contracts (deployer role, nonces from " + spike.chain.deployerStartNonce + "):");
p(table(["Contract", "Address", "Deploy tx", "Runtime size", "EXTCODEHASH"],
  Object.entries(spike.contracts).map(([k, c]) => [k, code(c.address), c.txHash ? code(c.txHash) : c.createdBy ?? "", c.codeSize ? n(c.codeSize) : "", code(c.extcodehash)])));
const dmc = spike.checks.delegationManager;
const d = spike.delegation;
h("Account and delegation:");
p(table(["Item", "Value"], [
  ["DelegationManager owner", `${code(dmc.owner)} (supervisor: ${yes(dmc.ownerIsSupervisor)}), paused ${dmc.paused}, VERSION ${dmc.version}`],
  ["DelegationManager EIP-712 domain", `chainId ${dmc.eip712DomainChainId} (domain hash computed with chain id ${dmc.domainUsesChainId}); domain hash ${code(dmc.domainHash)}`],
  ["HybridDeleGator account (ERC1967 proxy)", `${code(spike.checks.account.address)} -> impl ${code(spike.checks.account.implementationSlot)}; owner ${code(spike.checks.account.owner)} (director-1: ${yes(spike.checks.account.ownerIsDirector1)}); ${spike.checks.account.passkeys}`],
  ["Test token", `${code(spike.checks.token.address)} ${spike.checks.token.name} (${spike.checks.token.label}); account balance ${spike.checks.token.accountBalance}`],
  ["Delegation", `delegator account -> delegate ${code(d.delegate)} (agent-treasurer), root authority, salt ${d.salt}`],
  ["Caveats", d.caveats.map((c) => `${c.enforcer} (${c.meaning})`).join("; ")],
  ["Delegation hash (on-chain = off-chain)", `${code(d.delegationHashOnchain)} (${yes(d.delegationHashesMatch)})`],
  ["Typed-data hash signed by director-1", `${code(d.typedDataHash)}; isValidSignature returned ${code(d.erc1271Result)}`],
]));
h("Redemptions (agent-treasurer calls `DelegationManager.redeemDelegations`, recipient svc-shenzhen-components):");
p(table(["Step", "Tx", "Status", "Gas used", "Recipient balance after", "Spent (enforcer)"],
  spike.redemptions.map((r) => [r.description ?? r.label, code(r.hash), r.status, n(r.gasUsed), r.balancesAfter.recipient, r.balancesAfter.spent])));
const over = spike.redemptions[1];
p("");
p(`Over-cap attempt: eth_estimateGas returned ${over.estimateGas.rpcError ? `error code ${over.estimateGas.rpcError.code}` : "a value"} with revert ${code(over.estimateGas.revert?.reason)}; the transaction was then forced on-chain with a fixed gas limit and mined with status ${over.status}; eth_call replay at the parent block decoded ${code(over.replayAtParentBlock.revert?.reason)} (FISCO ignores the block tag, so this replay ran against the latest state, which the revert left unchanged: ${yes(over.stateUnchanged)}).`);

// ------------------------------------------------------------------------------------------------
h("### Runtime code hash: FISCO vs local anvil (london)");
p(compare.method);
p("");
const byName = {};
for (const c of compare.comparisons) for (const r of c.perContract) (byName[r.contract] ??= {})[c.anvilChainId] = r;
const ids = compare.comparisons.map((c) => c.anvilChainId);
p(table(["Contract", ...ids.map((i) => `vs anvil chain ${i}`), "Explanation (chain " + ids[0] + ")"],
  Object.entries(byName).map(([name, m]) => [name, ...ids.map((i) => (m[i] ? (m[i].extcodehashEqual ? "equal" : "differs") : "n/a")), m[ids[0]]?.explanation ?? ""])));
p("");
for (const c of compare.comparisons) {
  p(`- anvil chain ${c.anvilChainId}: same addresses ${yes(c.allAddressesEqual)}; identical runtime ${c.identicalRuntime.length}; differ only in immutables ${c.differOnlyInImmutables.length}${c.differOnlyInImmutables.length ? ` (${c.differOnlyInImmutables.join(", ")})` : ""}; differ otherwise ${c.differOtherwise.length}.`);
}

const readmePath = join(HERE, "README.md");
const readme = readFileSync(readmePath, "utf8");
const START = "<!-- generated:results:start -->";
const END = "<!-- generated:results:end -->";
const a = readme.indexOf(START);
const b = readme.indexOf(END);
if (a < 0 || b < 0) throw new Error("markers not found in README.md");
const next = `${readme.slice(0, a + START.length)}\n${lines.join("\n")}\n${readme.slice(b)}`;
writeFileSync(readmePath, next);
console.log(`rendered ${lines.length} lines into ${rel(readmePath)}`);
