#!/usr/bin/env node
// Reads the brand vector masters in public/brand and writes components/brand/paths.ts with their
// geometry (the S glyph and the wordmark; the dragon mark is retired), so marks can be inlined (currentColor inheritance, group-level animation).
// Run: node scripts/brand-to-tsx.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => readFileSync(join(root, "public/brand", f), "utf8");

function viewBox(svg) {
  return /viewBox="([^"]+)"/.exec(svg)[1];
}
function paths(svg, groupId) {
  const g = new RegExp(`<g id="${groupId}"[^>]*>([\\s\\S]*?)</g>`).exec(svg);
  if (!g) return [];
  return [...g[1].matchAll(/<path(?: id="([^"]+)")? d="([^"]+)"/g)].map((m) => ({ id: m[1] ?? groupId, d: m[2] }));
}

const glyph = read("yinglong-glyph.svg");
const wordmark = read("yinglong-wordmark.svg");
const ring = /<circle id="status-ring" cx="([^"]+)" cy="([^"]+)" r="([^"]+)"[^>]*stroke-width="([^"]+)"/.exec(wordmark);
const pearl = /<circle id="status-pearl" cx="([^"]+)" cy="([^"]+)" r="([^"]+)"/.exec(wordmark);

const out = {
  glyph: {
    viewBox: viewBox(glyph),
    spine: /<path d="([^"]+)"/.exec(glyph)[1],
  },
  wordmark: {
    viewBox: viewBox(wordmark),
    letters: paths(wordmark, "letters").map((p) => p.d),
    statusRing: { cx: Number(ring[1]), cy: Number(ring[2]), r: Number(ring[3]), strokeWidth: Number(ring[4]) },
    statusPearl: { cx: Number(pearl[1]), cy: Number(pearl[2]), r: Number(pearl[3]) },
  },
};

const target = join(root, "components/brand/paths.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/brand-to-tsx.mjs from public/brand/*.svg. Do not edit by hand.\n` +
    `export const BRAND = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`wrote ${target}`);
