"use client";

import { useEffect, useMemo, useRef } from "react";
import { useAgent } from "@/lib/api/hooks";
import { formatTime } from "@/lib/format";
import { metricCount, SITE } from "@/content/site-data";
import { useMotionOff } from "@/components/preferences";
import { useInView } from "./use-live";

/**
 * Counters: every value is generated. Bundle values come from docs/evidence/bundle.json (copied at
 * build time); the stopped-attack count is read live from GET /v1/challenge/attempts. Each number
 * counts up from zero once when the row scrolls into view, and is simply shown under reduced motion
 * or Pause motion. The count writes one text node per frame inside a contained box (no React
 * render per frame, no layout outside the box); five NumberFlow instances spinning at once dropped
 * frames while scrolling.
 */
export function Tickers() {
  const row = useRef<HTMLDListElement>(null);
  const inView = useInView(row);
  const motionOff = useMotionOff();
  const attempts = useAgent("challenge-attempts", (api) => api.challengeAttempts(), ["challenge"]);
  const stopped = useMemo(() => (attempts.data ? attempts.data.filter((a) => a.stoppedAt).length : null), [attempts.data]);
  const failed = SITE.metrics?.values["tests.failed"] ?? null;

  const items = [
    { key: "anchored", value: metricCount("evidence.anchored_receipts"), label: "receipts anchored on chain", source: "evidence bundle" },
    { key: "reverts", value: metricCount("evidence.reverts"), label: "attacks reverted by the enforcers on chain", source: "evidence bundle" },
    { key: "refused", value: metricCount("evidence.refused_offchain"), label: "requests refused before the chain", source: "evidence bundle" },
    { key: "attempts", value: stopped, label: "Judge's Challenge attempts stopped", source: "GET /v1/challenge/attempts, live" },
    {
      key: "tests",
      value: metricCount("tests.total"),
      label: failed && !failed.startsWith("0") ? `tests run (${failed.replace(/\s*\(.*$/, "")} failed)` : "tests run, all passing",
      source: "evidence bundle",
    },
  ].filter((i): i is typeof i & { value: number } => i.value !== null);

  if (!items.length) return null;
  const at = SITE.metrics?.generatedAt;
  return (
    <div className="grid gap-4">
      <dl ref={row} className="m-0 grid grid-cols-2 gap-x-6 gap-y-8 border-y border-line-1 py-8 sm:grid-cols-3 lg:grid-cols-5">
        {items.map((i) => (
          <div key={i.key} className="grid content-start gap-2">
            <dt className="order-2 text-13 leading-snug text-fg-2">{i.label}</dt>
            <dd className="order-1 m-0 font-mono text-[2.25rem] leading-none text-fg-0 sm:text-[2.75rem]">
              <CountUp value={i.value} run={inView && !motionOff} armed={!motionOff} />
            </dd>
            <dd className="order-3 m-0 text-11 text-fg-muted">{i.source}</dd>
          </div>
        ))}
      </dl>
      {at ? <p className="m-0 text-12 text-fg-muted">Evidence bundle generated by scripts/finalize, {formatTime(at)} HKT.</p> : null}
    </div>
  );
}

/** Counts from 0 to `value` once (ease-out, 1.1 s) when `run` turns true; the final value is in the HTML. */
function CountUp({ value, run, armed }: { value: number; run: boolean; armed: boolean }) {
  const el = useRef<HTMLSpanElement>(null);
  const done = useRef(false);
  useEffect(() => {
    const node = el.current;
    if (!node) return;
    if (!run || done.current) {
      // Waiting below the fold with motion on: start from zero; otherwise show the value.
      node.textContent = String(armed && !done.current ? 0 : value);
      return;
    }
    done.current = true;
    let raf = 0;
    const t0 = performance.now();
    const step = (t: number) => {
      const k = Math.min(1, (t - t0) / 1100);
      node.textContent = String(Math.round(value * (1 - (1 - k) ** 3)));
      if (k < 1) raf = requestAnimationFrame(step);
    };
    raf = requestAnimationFrame(step);
    return () => cancelAnimationFrame(raf);
  }, [value, run, armed]);
  return (
    <span ref={el} className="inline-block tabular-nums [contain:layout_paint]" style={{ minWidth: `${String(value).length}ch` }}>
      {value}
    </span>
  );
}
